-- Scala delle statistiche con il livello ------------------------------------------------

function Titans.NapeHP(config, classMult: number, level: number): number
	return math.floor(config.Titans.NapeHPBase * classMult * (1 + (level - 1) * config.Titans.NapeHPPerLevel))
end

function Titans.Damage(config, classMult: number, level: number): number
	return config.Titans.DamageBase * classMult * (1 + (level - 1) * config.Titans.DamagePerLevel)
end

function Titans.GetClass(id: string?)
	return id and Titans.Classes[id]
end

function Titans.GetBoss(id: string?)
	return id and Titans.Bosses[id]
end

return Titans
